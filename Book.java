class Book
{ private String id;
  private String title;
  private double price;

public String getId(){
	return this.id;
  }

public void setId(String id){
	this.id=id;
}

public String getTitle(){
	return this.title;
}

public void setTitle(String title){
	this.title=title;
}

public double getPrice(){
	return this.price;
}

public void setPrice(double price){
	this.price=price;
}

}