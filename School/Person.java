class  Person
{
	protected String ID;
	protected String NAME;
	protected Major M;

	Person(){
	}
	
	public String getID(){
		return this.ID;
	}

	public void setID(String ID){
		this.ID = ID ;
	}

	public String getNAME(){
		return this.NAME;
	}

	public void setNAME(String NAME){
		this.NAME = NAME ;
	}

	public Major getMAJOR(){
		return this.M;
	}
	public void setMAJOR(Major M){
		this. M = M ;
	}
}




